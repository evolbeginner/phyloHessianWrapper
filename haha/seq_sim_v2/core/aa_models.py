"""Empirical amino acid substitution models: JTT, WAG, PAM, BLOSUM62, LG, GENERAL.
Each model is defined by 190 relative substitution rates and 20 equilibrium frequencies."""

import numpy as np
from ._validators import (validate_aa_freqs, validate_state, validate_length,
                           validate_output_array, normalize_freqs)

NUM_AA = 20
NUM_AA_REL_RATES = 190
AA_CHARS = "ARNDCQEGHILKMFPSTWYV"
AA_ORDER = list(AA_CHARS)


class AAModel:
    """Amino acid model with symmetric eigendecomposition of the 20x20 Q-matrix."""

    def __init__(self, freqs, relative_rates):
        if len(freqs) != NUM_AA:
            raise ValueError(
                f"freqs must contain exactly {NUM_AA} amino acid frequencies, "
                f"got {len(freqs)}"
            )
        validate_aa_freqs(freqs, AA_ORDER)
        if len(relative_rates) != NUM_AA_REL_RATES:
            raise ValueError(
                f"relative_rates must contain exactly {NUM_AA_REL_RATES} values, "
                f"got {len(relative_rates)}"
            )
        for i, r in enumerate(relative_rates):
            if not np.isfinite(r):
                raise ValueError(
                    f"relative_rates must be finite, got rate[{i}]={r}"
                )
            if r < 0.0:
                raise ValueError(
                    f"relative_rates must be non-negative, got rate[{i}]={r}"
                )
        if all(r == 0.0 for r in relative_rates):
            raise ValueError("at least one relative rate must be positive")
        self.num_states = NUM_AA
        self.state_chars = AA_CHARS
        pi = np.array(freqs, dtype=np.float64)
        self.freq = pi
        self.add_freq = np.cumsum(pi)

        R = np.zeros((NUM_AA, NUM_AA))
        k = 0
        for i in range(NUM_AA - 1):
            for j in range(i + 1, NUM_AA):
                R[i][j] = R[j][i] = relative_rates[k]
                k += 1

        Q = R * pi[None, :]
        mean_rate = 0.0
        for i in range(NUM_AA):
            s = np.sum(Q[i])
            Q[i][i] = -s
            mean_rate += pi[i] * s
        Q /= mean_rate

        sqrt_pi = np.sqrt(pi)
        inv_sqrt_pi = 1.0 / sqrt_pi

        S = sqrt_pi[:, None] * Q * inv_sqrt_pi[None, :]
        asym = np.max(np.abs(S - S.T))
        if asym > 1e-12:
            raise FloatingPointError(
                f"AA reversible transform is unexpectedly asymmetric: {asym}"
            )
        S = 0.5 * (S + S.T)

        roots, U = np.linalg.eigh(S)

        self._roots = roots
        self._eigvecs = U
        self._sqrt_pi = sqrt_pi
        self._inv_sqrt_pi = inv_sqrt_pi

    def set_matrix(self, matrix, length):
        """Fill a flat array with cumulative transition probabilities.
        Each row last element is exactly 1.0."""
        validate_output_array(matrix, self.num_states * self.num_states)
        length = validate_length(length)
        m = matrix.reshape(self.num_states, self.num_states)
        if length == 0.0:
            m[:] = np.eye(self.num_states)
        else:
            E = self._eigvecs * np.exp(self._roots * length)[None, :]
            E = E @ self._eigvecs.T
            m[:] = E * (self._sqrt_pi[None, :] / self._sqrt_pi[:, None])
        min_prob = np.min(m)
        if min_prob < -1e-12:
            raise FloatingPointError(
                f"AA transition matrix contains significantly negative "
                f"probability: {min_prob}"
            )
        m[m < 0.0] = 0.0
        m /= m.sum(axis=1, keepdims=True)
        np.cumsum(m, axis=1, out=m)
        m[:, -1] = 1.0

    def set_vector(self, vector, state, length):
        """Fill a flat array with a single cumulative row of P(t).
        The last element is exactly 1.0."""
        validate_output_array(vector, self.num_states)
        length = validate_length(length)
        state = validate_state(state, self.num_states)
        v = vector[:self.num_states]
        if length == 0.0:
            v[:] = 0.0
            v[state] = 1.0
        else:
            E_row = self._eigvecs[state] * np.exp(self._roots * length)
            v[:] = E_row @ self._eigvecs.T
            v[:] *= self._sqrt_pi / self._sqrt_pi[state]
        min_prob = np.min(v)
        if min_prob < -1e-12:
            raise FloatingPointError(
                f"AA transition vector contains significantly negative "
                f"probability: {min_prob}"
            )
        v[v < 0.0] = 0.0
        s = v.sum()
        if s > 0.0:
            v /= s
        np.cumsum(v, out=v)
        v[-1] = 1.0


def create_aa_model(name, user_freqs=None, user_rates=None, equal_freqs=False):
    """Factory: create AAModel by name.  user_freqs overrides default frequencies."""
    name = name.upper()
    emp = _EMPIRICAL_MODELS.get(name)
    if emp is None and name != "GENERAL":
        raise ValueError(f"Unknown AA model: {name}")

    if name == "GENERAL":
        if user_rates is None:
            raise ValueError("GENERAL model requires user-supplied relative_rates")
        if user_freqs is None:
            raise ValueError("GENERAL model requires user-supplied freqs")
        rates = list(user_rates)
        freqs = list(user_freqs)
    else:
        rates = list(emp["rates"])
        if equal_freqs:
            freqs = [1.0 / NUM_AA] * NUM_AA
        elif user_freqs:
            freqs = list(user_freqs)
        else:
            freqs = list(emp["freqs"])

    normalize_freqs(freqs)
    return AAModel(freqs, rates)


